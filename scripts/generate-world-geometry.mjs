// D3. Generate Rust geometry constants from the authored Moonvale map data.
// Run: node scripts/generate-world-geometry.mjs [--check]
// Offline generation only. No runtime server data loading or client authority.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { AUTHORED_MAPS, MAP_IDS } from "../src/world/authored-maps.mjs";

const destination = fileURLToPath(new URL("../server/src/world_geometry_data.rs", import.meta.url));
const renderer = readFileSync(new URL("../src/browser/authored-world-renderer.mjs", import.meta.url), "utf8");
const preview = readFileSync(new URL("../src/world/authored-preview-collision.mjs", import.meta.url), "utf8");

function requireContract(source, marker, label) {
  if (!source.includes(marker)) throw new Error(`World geometry mismatch: ${label}. Update the shared geometry contract before regenerating.`);
}
requireContract(renderer, "const verticalGapY=4180, horizontalGateX=4130;", "renderer gate positions");
requireContract(renderer, "37,\"#494e46\"", "renderer wall thickness");
requireContract(preview, "const WALL_HALF_THICKNESS = 37 / 2;", "preview wall thickness");
requireContract(preview, "const GREYHAVEN_GATE_X = 4130;", "preview x gate");
requireContract(preview, "const GREYHAVEN_GATE_Y = 4180;", "preview y gate");
requireContract(preview, "const GATE_X_HALF_WIDTH = 73;", "preview x half-gap");
requireContract(preview, "const GATE_Y_HALF_HEIGHT = 68;", "preview y half-gap");

const moonvale = AUTHORED_MAPS[MAP_IDS.overworld];
const inn = AUTHORED_MAPS[MAP_IDS.tavern];
if (moonvale?.id !== "moonvale-overworld" || inn?.id !== "red-lion-inn"
  || moonvale.width !== 8192 || moonvale.height !== 8192
  || inn.width !== 780 || inn.height !== 620) throw new Error("Unexpected map identity or dimensions");
if (moonvale.buildings.length > 128 || inn.furniture.length > 128
  || moonvale.river.points.length > 128 || moonvale.bridges.length > 32)
  throw new Error("Authored geometry exceeds bounded manifest capacity");

function number(value) {
  if (!Number.isSafeInteger(value) || Math.abs(value) > 100000)
    throw new Error("Unsafe coordinate in authored map manifest");
  return `${value}.0`;
}
function rect(value) {
  return `Rect { x: ${number(value.x)}, y: ${number(value.y)}, w: ${number(value.w)}, h: ${number(value.h)} }`;
}
function point(value) {
  if (!Array.isArray(value) || value.length !== 2) throw new Error("Malformed river point");
  return `Point { x: ${number(value[0])}, y: ${number(value[1])} }`;
}
function emit(name, type, entries) {
  return `pub(super) const ${name}: [${type}; ${entries.length}] = [\n${entries.map(x => `    ${x},`).join("\n")}\n];\n`;
}

const solids = inn.furniture.filter(x => x.kind !== "rug");
const out = [
  "// Generated by scripts/generate-world-geometry.mjs; DO NOT HAND EDIT.",
  "// Mirror of authored-maps.mjs for dormant server-side D3 geometry tests.",
  "// Changing authored world or preview wall constants requires regeneration.",
  `pub(super) const MOONVALE_BOUNDS: (f32, f32) = (${number(moonvale.width)}, ${number(moonvale.height)});`,
  `pub(super) const RED_LION_BOUNDS: (f32, f32) = (${number(inn.width)}, ${number(inn.height)});`,
  `pub(super) const GREYHAVEN_CITY: Rect = ${rect(moonvale.city)};`,
  `pub(super) const RIVER_WIDTH: f32 = ${number(moonvale.river.width)};`,
  "pub(super) const WALL_HALF_THICKNESS: f32 = 18.5;",
  "pub(super) const GATE_X: f32 = 4130.0;",
  "pub(super) const GATE_Y: f32 = 4180.0;",
  "pub(super) const GATE_X_HALF_WIDTH: f32 = 73.0;",
  "pub(super) const GATE_Y_HALF_HEIGHT: f32 = 68.0;",
  emit("BUILDINGS", "Rect", moonvale.buildings.map(rect)),
  emit("INN_SOLIDS", "Rect", solids.map(rect)),
  emit("RIVER_POINTS", "Point", moonvale.river.points.map(point)),
  emit("BRIDGES", "Rect", moonvale.bridges.map(rect)),
  "",
].join("\n");
if (process.argv.includes("--check")) {
  if (readFileSync(destination, "utf8").replace(/\r\n/g, "\n") !== out) {
    console.error("World geometry generated Rust constants are stale.");
    process.exitCode = 1;
  } else {
    console.log("World geometry Rust constants match authored map.");
  }
} else {
  writeFileSync(destination, out);
  console.log("Generated", destination);
}
