//! Inactive, server-internal geometry foundation for future elemental spells.
//! The caller must authenticate a cast, select targets through authoritative
//! interest/collision data, and sweep the proposed displacement against world
//! colliders before changing fighter or item state. No client input is accepted.

pub const MAX_RADIUS: f32 = 512.0;
pub const MAX_DISPLACEMENT: f32 = 64.0;
const MAX_COORDINATE: f32 = 1_000_000.0;
const MAX_COLLIDER_RADIUS: f32 = 128.0;
const EPSILON: f32 = 1e-6;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Element {
    Fire,
    Ice,
    Lightning,
    Wind,
    Arcane,
}

#[derive(Debug, Clone, Copy)]
pub struct AuthoritativeImpulse {
    pub zone_id: u32,
    pub origin_x: f32,
    pub origin_y: f32,
    pub radius: f32,
    pub displacement: f32,
    /// Generated by the trusted server for repeatable coincident-origin pushes.
    pub seed: u32,
    pub element: Element,
}

#[derive(Debug, Clone, Copy)]
pub struct ImpulseTarget {
    pub entity_id: u32,
    pub zone_id: u32,
    pub x: f32,
    pub y: f32,
    pub collider_radius: f32,
    /// Immobile scenery and protected actors cannot receive a displacement.
    pub mobile: bool,
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct ProposedDisplacement {
    pub entity_id: u32,
    pub dx: f32,
    pub dy: f32,
}

fn valid_coordinate(value: f32) -> bool {
    value.is_finite() && value.abs() <= MAX_COORDINATE
}

/// Calculate one bounded displacement without modifying combat/world state.
///
/// This is NOT collision resolution: a future integration must sweep against the
/// trusted map/door geometry, check spell ownership and cooldown/mana authority,
/// and reject displacement through blockers or across zone boundaries.
pub fn radial_impulse(
    source: &AuthoritativeImpulse,
    target: &ImpulseTarget,
) -> Option<ProposedDisplacement> {
    if source.zone_id == 0
        || target.entity_id == 0
        || source.zone_id != target.zone_id
        || !target.mobile
        || !valid_coordinate(source.origin_x)
        || !valid_coordinate(source.origin_y)
        || !valid_coordinate(target.x)
        || !valid_coordinate(target.y)
        || !source.radius.is_finite()
        || source.radius <= 0.0
        || source.radius > MAX_RADIUS
        || !source.displacement.is_finite()
        || source.displacement <= 0.0
        || source.displacement > MAX_DISPLACEMENT
        || !target.collider_radius.is_finite()
        || !(0.0..=MAX_COLLIDER_RADIUS).contains(&target.collider_radius)
    {
        return None;
    }

    let dx = target.x - source.origin_x;
    let dy = target.y - source.origin_y;
    let reach = source.radius + target.collider_radius;
    if dx.abs() >= reach || dy.abs() >= reach {
        return None;
    }

    let distance_sq = dx * dx + dy * dy;
    if distance_sq >= reach * reach {
        return None;
    }
    let distance = distance_sq.sqrt();
    let magnitude = source.displacement * (1.0 - distance / reach);
    if magnitude <= 0.0 {
        return None;
    }
    // Stable tie-break for an entity exactly at the blast center. No global RNG.
    let (unit_x, unit_y) = if distance <= EPSILON {
        match (source.seed ^ target.entity_id) & 3 {
            0 => (1.0, 0.0),
            1 => (0.0, 1.0),
            2 => (-1.0, 0.0),
            _ => (0.0, -1.0),
        }
    } else {
        (dx / distance, dy / distance)
    };

    Some(ProposedDisplacement {
        entity_id: target.entity_id,
        dx: unit_x * magnitude,
        dy: unit_y * magnitude,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn source() -> AuthoritativeImpulse {
        AuthoritativeImpulse {
            zone_id: 7,
            origin_x: 100.0,
            origin_y: 100.0,
            radius: 90.0,
            displacement: 40.0,
            seed: 12345,
            element: Element::Wind,
        }
    }

    fn target() -> ImpulseTarget {
        ImpulseTarget {
            entity_id: 42,
            zone_id: 7,
            x: 145.0,
            y: 100.0,
            collider_radius: 10.0,
            mobile: true,
        }
    }

    #[test]
    fn falloff_is_bounded_and_points_away_from_the_center() {
        let near = radial_impulse(&source(), &target()).unwrap();
        assert!((near.dx - 22.0).abs() < 0.001);
        assert_eq!(near.dy, 0.0);
        let mut farther = target();
        farther.x = 185.0;
        let far = radial_impulse(&source(), &farther).unwrap();
        assert!(far.dx > 0.0 && far.dx < near.dx);
        farther.x = 200.0;
        assert!(radial_impulse(&source(), &farther).is_none());
    }

    #[test]
    fn zone_and_immobility_rules_fail_closed() {
        let mut t = target();
        t.zone_id = 8;
        assert!(radial_impulse(&source(), &t).is_none());
        t.zone_id = 7;
        t.mobile = false;
        assert!(radial_impulse(&source(), &t).is_none());
        t.mobile = true;
        t.entity_id = 0;
        assert!(radial_impulse(&source(), &t).is_none());
    }

    #[test]
    fn rejects_nonfinite_oversized_and_invalid_geometry() {
        let mut s = source();
        s.displacement = f32::INFINITY;
        assert!(radial_impulse(&s, &target()).is_none());
        s = source();
        s.radius = 513.0;
        assert!(radial_impulse(&s, &target()).is_none());
        s = source();
        s.origin_x = f32::NAN;
        assert!(radial_impulse(&s, &target()).is_none());
        let mut t = target();
        t.x = f32::INFINITY;
        assert!(radial_impulse(&source(), &t).is_none());
        t = target();
        t.collider_radius = -1.0;
        assert!(radial_impulse(&source(), &t).is_none());
    }

    #[test]
    fn coincident_positions_use_reproducible_cardinal_direction() {
        let mut t = target();
        t.x = 100.0;
        t.y = 100.0;
        let a = radial_impulse(&source(), &t).unwrap();
        let b = radial_impulse(&source(), &t).unwrap();
        assert_eq!(a, b);
        assert!((a.dx * a.dx + a.dy * a.dy - 1600.0).abs() < 0.01);
    }

    #[test]
    fn cannot_change_authoritative_target_state() {
        let t = target();
        let original_x = t.x;
        let _candidate = radial_impulse(&source(), &t).unwrap();
        assert_eq!(t.x, original_x);
    }
}
