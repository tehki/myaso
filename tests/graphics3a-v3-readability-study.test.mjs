import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync,readdirSync} from "node:fs";
import {createHash} from "node:crypto";
const root=new URL("../",import.meta.url);
const art="docs/art/silver-spartan-v3-readability-study/";
const bytes=(path)=>readFileSync(new URL(path,root));
const sha=b=>createHash("sha256").update(b).digest("hex");
const m=JSON.parse(bytes(art+"spartan_v3_readability_study_manifest.json"));
const pose=JSON.parse(bytes(art+"original_v3_vs_lighting_study_rig_audit.json"));
test("original Silver V3 lighting study uses the genuine rig, unchanged action and no gameplay",()=>{
 assert.equal(m.originalRigBones,22);
 assert.equal(m.originalSourceSha256,"d679fccd00df868d600b4c5e2fcf8a4a46cc062dbd432be5b6a7f533eb30141f");
 assert.equal(m.actionDurationMs,380);
 assert.equal(m.onlyCyclesLightingChanged,true);
 assert.equal(m.noCameraOrActorRootChanges,true);
 assert.equal(m.noCombatOrPhysicsChanges,true);
 assert.equal(m.originalV3AtlasUnmodified,true);
 assert.equal(m.sourceOriginalMeshNotBundled,true);
 assert.equal(m.nativeMultiplayerValidated,false);
 assert.equal(m.gameplayScaleValidated,false);
 assert.equal(m.defaultRendererActivated,false);
 assert.equal(m.preAlphaIncluded,false);
 assert.equal(m.humanVisualApproved,false);
 assert.equal(pose.authoritativeKickPhaseMs.join(","),"90,70,220");
 assert.deepEqual(pose.priorSamples,pose.proposedSamples);
 assert.equal(pose.candidateSupportToeMaxSourceDrift<=0.002,true);
});
test("full 64-cell eight-facing Cycles study improves readability without modifying alpha",()=>{
 assert.equal(m.renderedCells,64);
 assert.equal(m.sourceFramesPerDirection,8);
 assert.equal(m.directionCount,8);
 assert.deepEqual(m.studyAtlasPx,[1280,1280]);
 assert.deepEqual(m.sourceCellPx,[160,160]);
 assert.equal(m.sampledFrames.length,64);
 assert.deepEqual(new Set(m.sampledFrames.map(x=>x.direction)),new Set([0,1,2,3,4,5,6,7]));
 assert.equal(m.allCellsIdenticalSilhouette,true);
 assert.ok(m.sampledFrames.every(x=>x.sourceAlphaIdentical && x.visiblePixels>300 && x.lumaGainPct>5));
 assert.ok(m.minimumSourceLumaGainPct>5);
 assert.ok(m.averageSourceLumaGainPct>5);
 const baseline=bytes("docs/art/silver-spartan-contact-recoil-v3/silver_spartan_contact_recoil_v3_p0.webp");
 assert.equal(sha(baseline),m.originalV3AtlasSha256);
 assert.equal(m.originalV3AtlasSha256,"a6001a61c9cd48aa5b34ff7a7ecccb071bd6a3c6465ec5fd0cabffb4d3d1d747");
 const atlas=bytes(art+"silver_spartan_v3_readable_light_study_8x8.webp");
 assert.equal(sha(atlas),m.newStudyAtlasSha256);
 assert.equal(atlas.subarray(8,12).toString("ascii"),"WEBP");
 assert.notEqual(sha(atlas),sha(baseline));
 assert.equal(sha(bytes(art+"Graphics3A_Silver_Spartan_V3_ReadableLight_Study_source.blend")),m.studyBlendSha256);
 const gif=bytes(art+"silver_spartan_v3_normal_vs_light_study_8way_380ms.gif");
 assert.equal(gif.subarray(0,4).toString(),"GIF8");
 assert.equal(sha(gif),m.comparisonGifSha256);
});
test("isolated opt-in lighting does not change default renderer, physics or owner Silver assets",()=>{
 const t=bytes("tools/art/author_silver_kick_dash_p0.py").toString();
 assert.match(t,/--spartan-v3-readable-light/);
 assert.match(t,/assert not args.spartan_v3_readable_light or args.spartan_contact_recoil_v3/);
 assert.match(t,/295 if args.spartan_v3_readable_light else 210/);
 assert.match(t,/280 if args.spartan_v3_readable_light else 180/);
 assert.match(t,/\.88 if args.spartan_v3_readable_light else \.65/);
 const artDir=new URL(art,root);
 assert.ok(!readdirSync(artDir).some(x=>x.endsWith(".glb")));
});
